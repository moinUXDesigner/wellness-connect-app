export function lookupStateForCity(city: string): string | null {
  const normalized = city.trim().toLowerCase();
  if (!normalized) return null;

  const match = Object.entries(indiaCityToState).find(([name]) => name.toLowerCase() === normalized);
  return match ? match[1] : null;
}
